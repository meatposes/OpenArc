NAME_TO_CODE = {v: k for k, v in LANGUAGES.items()}


def to_code(language: str | None) -> str | None:
    """'en', 'EN', 'English' or '<|en|>' -> 'en'. Unknown -> ValueError."""
    if not language:
        return None
    s = language.strip().lower().removeprefix("<|").removesuffix("|>")
    if s in LANGUAGES:
        return s
    if s in NAME_TO_CODE:
        return NAME_TO_CODE[s]
    raise ValueError(f"Unknown language for Whisper: {language!r}")


def from_token(token: str | None) -> str | None:
    """'<|pl|>' -> 'pl'."""
    if not token:
        return None
    return token.strip().removeprefix("<|").removesuffix("|>") or None
